"""Write docs/coverage.md: what the bundled catalog covers for each brain and each stack.

Run `python scripts/coverage.py` after a catalog change, or `--check` to fail when the
page is out of date. The script reads only the bundled catalog and opens no network.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from openguildkit.catalog import load_catalog  # noqa: E402 - INTENTIONAL(#522): after sys.path is set above
from openguildkit.references import load_references  # noqa: E402 - INTENTIONAL(#522): after sys.path is set above

OUTPUT = ROOT / "docs" / "coverage.md"


def active_packs(pack_ids, packs):
    """The packs a pattern activates, dependencies included."""
    active, pending = set(), list(pack_ids)
    while pending:
        pack_id = pending.pop()
        if pack_id not in active:
            active.add(pack_id)
            pending.extend(packs[pack_id].get("depends_on", []))
    return active


def is_stack_pattern(pattern):
    return bool(pattern.get("match", {}).get("stack"))


def brain_rows(catalog, families):
    references = [record for family in families.values() for record in family["references"]]
    rows = []
    for brain in sorted(catalog["boards"]):
        tagged = [record for record in references if brain in record.get("brains", [])]
        applied = [record for record in tagged if record.get("packs")]
        patterns = [pattern for pattern in catalog["patterns"].values() if brain in pattern["roles"]]
        packs = set()
        for pattern in patterns:
            packs |= active_packs(pattern["packs"], catalog["packs"])
        rows.append({
            "brain": brain,
            "references": len(tagged),
            "applied": len(applied),
            "documentary": sorted(record["id"] for record in tagged if not record.get("packs")),
            "methods": sum(1 for pattern in patterns if not is_stack_pattern(pattern)),
            "stack_patterns": sum(1 for pattern in patterns if is_stack_pattern(pattern)),
            "packs": len(packs),
            "rules": sum(len(catalog["packs"][pack_id]["rules"]) for pack_id in packs),
        })
    return rows


def stack_rows(catalog):
    rows = []
    for pattern in catalog["patterns"].values():
        if not is_stack_pattern(pattern):
            continue
        packs = active_packs(pattern["packs"], catalog["packs"])
        rows.append({
            "pattern": pattern["id"],
            "stack": " + ".join(" / ".join(group) for group in pattern["match"]["stack"]),
            "packs": ", ".join(sorted(packs)),
            "rules": sum(len(catalog["packs"][pack_id]["rules"]) for pack_id in packs),
        })
    return sorted(rows, key=lambda row: row["pattern"])


def sector_rows(catalog):
    """The patterns each sector preselects without a stack, and the rules they activate."""
    rows = []
    for sector_id in sorted(catalog["sectors"]):
        patterns = [
            pattern for pattern in catalog["patterns"].values()
            if sector_id in pattern.get("match", {}).get("sectors", []) and not is_stack_pattern(pattern)
        ]
        packs = set()
        for pattern in patterns:
            packs |= active_packs(pattern["packs"], catalog["packs"])
        rows.append({
            "sector": sector_id,
            "patterns": ", ".join(sorted(pattern["id"] for pattern in patterns)) or "none",
            "packs": ", ".join(sorted(packs)) or "none",
            "rules": sum(len(catalog["packs"][pack_id]["rules"]) for pack_id in packs),
        })
    return rows


def check_rows(catalog):
    """Each pack's rules, the rules with a machine check and those whose `manual` says why a person verifies them."""
    return [
        {
            "pack": pack_id,
            "rules": len(pack["rules"]),
            "machine": sum(1 for rule in pack["rules"] if "check" in rule),
            "manual": sum(1 for rule in pack["rules"] if "manual" in rule),
        }
        for pack_id, pack in sorted(catalog["packs"].items())
    ]


def render(catalog, families):
    brains = brain_rows(catalog, families)
    lines = [
        "# Catalog coverage",
        "",
        "For: a contributor or reviewer who looks for what the catalog covers and what it does not.",
        "",
        "Generated by `python scripts/coverage.py` from the bundled catalog. Do not edit this page by hand: "
        "`tests/test_coverage.py` fails when it is out of date.",
        "",
        "A reference is *applied* when at least one pack names it, and *documentary* otherwise. "
        "A method is a pattern without a stack, preselected for its roles or, for a regulation, for its sectors; "
        "a stack pattern matches technologies. "
        "Packs and rules count what the brain's patterns activate, dependencies included.",
        "",
        "## By brain",
        "",
        "| Brain | References | Applied | Documentary | Methods | Stack patterns | Packs | Rules |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in brains:
        lines.append(
            f"| {row['brain']} | {row['references']} | {row['applied']} | {len(row['documentary'])} "
            f"| {row['methods']} | {row['stack_patterns']} | {row['packs']} | {row['rules']} |"
        )
    lines += [
        "",
        "## By stack",
        "",
        "| Stack pattern | Technologies | Packs | Rules |",
        "|---|---|---|---:|",
    ]
    for row in stack_rows(catalog):
        lines.append(f"| {row['pattern']} | {row['stack']} | {row['packs']} | {row['rules']} |")
    lines += [
        "",
        "## By sector",
        "",
        "Patterns that a sector preselects at `init` and in `recommend`, for the person to confirm or decline.",
        "",
        "| Sector | Preselected patterns | Packs | Rules |",
        "|---|---|---|---:|",
    ]
    for row in sector_rows(catalog):
        lines.append(f"| {row['sector']} | {row['patterns']} | {row['packs']} | {row['rules']} |")
    checks = check_rows(catalog)
    lines += [
        "",
        "## Machine checks by pack",
        "",
        f"{sum(row['machine'] for row in checks)} of {sum(row['rules'] for row in checks)} rules carry a machine check "
        "that `task verify` evaluates. A rule without one either says in `manual` why only a person can verify it, "
        "such as a record kept outside the repository, or is answered in the task result.",
        "",
        "| Pack | Rules | Machine checks | Verified by a person, reason given |",
        "|---|---:|---:|---:|",
    ]
    lines += [f"| {row['pack']} | {row['rules']} | {row['machine']} | {row['manual']} |" for row in checks]
    lines += [
        "",
        "## Not turned into rules",
        "",
        "SOC 2 has no pack, by decision. A SOC 2 report is an examination of controls at a service organization "
        "that a CPA reports on (AICPA, [System and Organization Controls]"
        "(https://www.aicpa-cima.com/topic/audit-assurance/audit-and-assurance-greater-than-soc-2), read 2026-11-22), "
        "not a list of requirements on the code. The organization controls such an examination looks at are asked "
        "on each change by the `iso-27001` pack and its Annex A rules, which a team under SOC 2 can select; the "
        "`soc-2` reference stays documentary.",
        "",
        "## To cover",
        "",
        "Documentary references of each brain: sources that no pack turns into rules yet. "
        "Start a new pack from a real use, name its context, its primary source and at least one piece of evidence the team can check.",
        "",
    ]
    for row in brains:
        documentary = ", ".join(f"`{record_id}`" for record_id in row["documentary"]) or "none"
        lines += [f"### {row['brain']}", "", documentary, ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if docs/coverage.md is not current.")
    args = parser.parse_args(argv)
    text = render(load_catalog(), load_references())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("docs/coverage.md is out of date. Run python scripts/coverage.py.", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
